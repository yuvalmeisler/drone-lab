// למשל video: '/videos/evo/props.mp4' — או קישור YouTube.

export type Difficulty = 'קל' | 'בינוני' | 'מתקדם'

/** שאלה שקופצת על הסרטון: הסרטון נעצר ב-at שניות וממשיך אחרי התשובה */
export interface VideoQuiz {
  at: number
  question: string
  options: string[]
  /** האינדקס של התשובה הנכונה ב-options */
  answer: number
}

/** סוג האייקון שמצויר ליד הרכיב בתמונת ההסבר */
export type PartIcon =
  | 'prop' | 'motor' | 'mark' | 'lock' | 'screw' | 'screwdriver' | 'pry' | 'tweezers'
  | 'gimbal' | 'camera' | 'lens' | 'cover' | 'button' | 'port' | 'dots' | 'antenna'
  | 'sensor' | 'frame' | 'leg' | 'case' | 'speaker' | 'stick' | 'cable' | 'battery'

/** רכיב שמשתתף בפירוק — מופיע בתמונת "רכיבים בפירוק" שליד הסרטון */
export interface Part {
  name: string
  icon: PartIcon
  /** הסבר קצר: מה הרכיב ולמה צריך להיזהר איתו */
  desc: string
}

export interface Task {
  id: string
  title: string
  summary: string
  difficulty: Difficulty
  minutes: number
  tools: string[]
  steps: string[]
  tip?: string
  /** סרטון אחד או כמה (נתיב ב-public/videos או קישור YouTube) */
  video?: string | string[]
  /** שאלות על הסרטון (לסרטון הראשון) */
  quizzes?: VideoQuiz[]
  /** הרכיבים שבהם נוגעים בפירוק — מהם נבנית תמונת ההסבר (npm run parts) */
  components?: Part[]
}

